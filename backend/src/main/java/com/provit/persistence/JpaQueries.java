package com.provit.persistence;

/** Native projections and PostgreSQL-specific atomic operations. Entity CRUD uses JPA. */
public final class JpaQueries {
    private JpaQueries() {}

    public static final String RESUME_JOB =
            """
            SELECT O.OCCUPATION_CODE, O.OCCUPATION_NAME, J.JOB_CODE, J.JOB_NAME
            FROM T_JOB J
            JOIN T_OCCUPATION O ON O.OCCUPATION_CODE = J.OCCUPATION_CODE
            WHERE O.OCCUPATION_CODE = :occupationCode
            AND J.JOB_CODE = :jobCode
            """;

    public static final String RESUME_DETAIL =
            """
SELECT R.RESUME_NUM, R.USER_NUM, R.RESUME_TITLE, R.OCCUPATION_CODE, O.OCCUPATION_NAME, R.JOB_CODE, J.JOB_NAME, R.HIGHEST_LEVEL, R.MOTIVATION, R.DESIRED_LOCATION, R.DESIRED_WORK_TYPE, R.CREATED_AT, R.UPDATED_AT
FROM T_RESUME R
LEFT JOIN T_OCCUPATION O ON O.OCCUPATION_CODE = R.OCCUPATION_CODE
LEFT JOIN T_JOB J ON J.JOB_CODE = R.JOB_CODE
AND J.OCCUPATION_CODE = R.OCCUPATION_CODE
WHERE R.RESUME_NUM = :resumeNum
AND R.USER_NUM = :userNum
""";

    public static final String MAIN_RESUME =
            """
SELECT R.RESUME_NUM, R.RESUME_TITLE, R.OCCUPATION_CODE, O.OCCUPATION_NAME, R.JOB_CODE, J.JOB_NAME
FROM T_USER U
JOIN T_RESUME R ON R.RESUME_NUM = U.MAIN_RESUME_NUM
AND R.USER_NUM = U.USER_NUM
LEFT JOIN T_OCCUPATION O ON O.OCCUPATION_CODE = R.OCCUPATION_CODE
LEFT JOIN T_JOB J ON J.JOB_CODE = R.JOB_CODE
AND J.OCCUPATION_CODE = R.OCCUPATION_CODE
WHERE U.USER_NUM = :userNum
AND U.USER_IS_DELETED = 0
""";

    public static final String POST_DETAIL =
            """
SELECT p.POST_NUM, p.CATEGORY_NUM, c.CATEGORY_NAME, p.USER_NUM, u.USER_NICKNAME, p.POST_TITLE, p.POST_CONTENT, p.POST_LIKE_COUNT, p.VIEW_COUNT, p.POST_FILE, p.POST_DATE, CASE
WHEN p.POST_TITLE = '관리자에 의해 블라인드 처리된 게시물입니다.'
OR EXISTS ( SELECT 1
FROM T_REPORT r
WHERE r.TARGET_TYPE = 'POST'
AND r.TARGET_NUM = p.POST_NUM
AND r.REPORT_STATUS = 'RESOLVED' )
THEN 1
ELSE 0 END AS isBlinded
FROM T_POST p
JOIN T_CATEGORY c ON p.CATEGORY_NUM = c.CATEGORY_NUM
JOIN T_USER u ON p.USER_NUM = u.USER_NUM
WHERE p.POST_NUM = :postNum
""";

    public static final String COMMENT_LIST =
            """
SELECT C.COMMENT_NUM AS commentNum, C.POST_NUM AS postNum, C.USER_NUM AS userNum, C.COMMENT_CONTENT AS commentContent, TO_CHAR(C.COMMENT_DATE, 'YYYY-MM-DD HH24:MI:SS') AS commentDate, U.USER_NICKNAME AS userNickname, C.PARENT_COMMENT_NUM AS parentCommentNum, C.IS_DELETED AS isDeleted
FROM T_COMMENT C
JOIN T_USER U ON C.USER_NUM = U.USER_NUM
WHERE C.POST_NUM = :postNum
ORDER BY COALESCE(C.PARENT_COMMENT_NUM, C.COMMENT_NUM) ASC, C.COMMENT_NUM ASC
""";

    public static final String COMMENT_MY_LIST =
            """
SELECT C.COMMENT_NUM AS commentNum, C.POST_NUM AS postNum, C.USER_NUM AS userNum, C.COMMENT_CONTENT AS commentContent, TO_CHAR(C.COMMENT_DATE, 'YYYY-MM-DD HH24:MI:SS') AS commentDate, C.PARENT_COMMENT_NUM AS parentCommentNum, C.IS_DELETED AS isDeleted, P.POST_TITLE AS postTitle, U.USER_NICKNAME AS userNickname
FROM T_COMMENT C
JOIN T_POST P ON C.POST_NUM = P.POST_NUM
JOIN T_USER U ON C.USER_NUM = U.USER_NUM
WHERE C.USER_NUM = :value
AND C.IS_DELETED = 0
ORDER BY C.COMMENT_DATE DESC, C.COMMENT_NUM DESC
""";

    public static final String USER_PREFERENCE =
            """
SELECT U.USER_NUM AS userNum, U.USER_NICKNAME AS userNickname, U.JOB_CODE AS jobCode, J.JOB_NAME AS jobName, U.OCCUPATION_CODE AS occupationCode, O.OCCUPATION_NAME AS occupationName
FROM T_USER U
LEFT JOIN T_JOB J ON U.JOB_CODE = J.JOB_CODE
LEFT JOIN T_OCCUPATION O ON U.OCCUPATION_CODE = O.OCCUPATION_CODE
WHERE U.USER_NUM = :userNum
AND U.USER_IS_DELETED = 0
""";

    public static final String INTERVIEW_PREFERENCE =
            """
            SELECT U.USER_NUM, U.OCCUPATION_CODE, O.OCCUPATION_NAME, U.JOB_CODE, J.JOB_NAME
            FROM T_USER U
            LEFT JOIN T_OCCUPATION O ON U.OCCUPATION_CODE = O.OCCUPATION_CODE
            LEFT JOIN T_JOB J ON U.JOB_CODE = J.JOB_CODE
            WHERE U.USER_NUM = :userNum
            AND U.USER_IS_DELETED = 0
            """;

    public static final String REVIEW_IMPROVEMENTS =
            """
SELECT I.REVIEW_DOCUMENT_NUM, I.DISPLAY_ORDER, I.SECTION_NAME AS SECTION, I.IMPROVEMENT_TITLE AS TITLE, I.ISSUE_CONTENT AS ISSUE, I.ORIGINAL_CONTENT AS ORIGINAL, I.SUGGESTED_CONTENT AS SUGGESTION, I.REASON_CONTENT AS REASON
FROM T_REVIEW_IMPROVEMENT I
JOIN T_REVIEW_DOCUMENT D ON D.REVIEW_DOCUMENT_NUM = I.REVIEW_DOCUMENT_NUM
WHERE D.REVIEW_NUM = :reviewNum
ORDER BY I.REVIEW_DOCUMENT_NUM, I.DISPLAY_ORDER
""";

    public static final String REVIEW_SOURCES =
            """
SELECT S.CONSISTENCY_NUM, S.REVIEW_NUM, S.REVIEW_DOCUMENT_NUM, S.DISPLAY_ORDER, D.DOCUMENT_TYPE, S.SECTION_NAME AS SECTION, S.SOURCE_CONTENT AS TEXT, S.PAGE_NUMBER
FROM T_REVIEW_SOURCE S
JOIN T_REVIEW_DOCUMENT D ON D.REVIEW_DOCUMENT_NUM = S.REVIEW_DOCUMENT_NUM
AND D.REVIEW_NUM = S.REVIEW_NUM
WHERE S.REVIEW_NUM = :reviewNum
ORDER BY S.CONSISTENCY_NUM, S.DISPLAY_ORDER
""";

    public static final String RECRUITMENT_UPSERT =
            """
INSERT INTO T_RECRUITMENT ( SARAMIN_JOB_ID, COMPANY_NAME, TITLE, JOB_URL, LOCATION_NAME, JOB_NAME, EXPERIENCE_LEVEL, EXPIRATION_DATE, CLOSE_TYPE, IS_ACTIVE )
VALUES ( :saraminJobId, :companyName, :title, :jobUrl, :locationName, :jobName, :experienceLevel, :expirationDate, :closeType, COALESCE(:isActive, 1) )
ON CONFLICT (SARAMIN_JOB_ID)
DO UPDATE SET COMPANY_NAME = EXCLUDED.COMPANY_NAME, TITLE = EXCLUDED.TITLE, JOB_URL = EXCLUDED.JOB_URL, LOCATION_NAME = EXCLUDED.LOCATION_NAME, JOB_NAME = EXCLUDED.JOB_NAME, EXPERIENCE_LEVEL = EXCLUDED.EXPERIENCE_LEVEL, EXPIRATION_DATE = EXCLUDED.EXPIRATION_DATE, CLOSE_TYPE = EXCLUDED.CLOSE_TYPE, IS_ACTIVE = EXCLUDED.IS_ACTIVE
""";

    public static final String SCRAP_INSERT =
            """
            INSERT INTO T_JOB_SCRAP ( RECRUITMENT_NUM, USER_NUM, CREATED_AT )
            VALUES ( :recruitmentNum, :userNum, LOCALTIMESTAMP )
            ON CONFLICT (RECRUITMENT_NUM, USER_NUM) DO NOTHING
            """;

    public static final String EXPIRE_RECRUITMENTS =
            """
            UPDATE T_RECRUITMENT
            SET IS_ACTIVE = 0
            WHERE IS_ACTIVE = 1
            AND ( (EXPIRATION_DATE IS NOT NULL
            AND EXPIRATION_DATE < LOCALTIMESTAMP)
            OR (EXPIRATION_DATE IS NULL
            AND CREATED_AT < LOCALTIMESTAMP - INTERVAL '60 days') )
            """;

    public static final String PURGE_RECRUITMENTS =
            """
            DELETE
            FROM T_RECRUITMENT R
            WHERE R.IS_ACTIVE = 0
            AND ( (R.EXPIRATION_DATE IS NOT NULL
            AND R.EXPIRATION_DATE < LOCALTIMESTAMP - INTERVAL '180 days')
            OR (R.EXPIRATION_DATE IS NULL
            AND R.CREATED_AT < LOCALTIMESTAMP - INTERVAL '180 days') )
            AND NOT EXISTS ( SELECT 1
            FROM T_JOB_SCRAP S
            WHERE S.RECRUITMENT_NUM = R.RECRUITMENT_NUM )
            """;
}
