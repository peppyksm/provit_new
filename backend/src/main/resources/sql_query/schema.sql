-- ================================================================================
-- 3. AI 원클릭 첨삭 도메인
-- ================================================================================

-- 3-1. 통합 첨삭 요청 및 종합 피드백
CREATE TABLE T_DOCUMENT_REVIEW (
    REVIEW_NUM          BIGINT          DEFAULT nextval('seq_t_document_review') PRIMARY KEY,
    USER_NUM            INTEGER           NOT NULL REFERENCES T_USER(USER_NUM) ON DELETE CASCADE,
    REQUEST_ID          VARCHAR(36),
    REQUEST_HASH        VARCHAR(64),
    REVIEW_TITLE        VARCHAR(200)  NOT NULL,
    REVIEW_STATUS       VARCHAR(20)   DEFAULT 'PROCESSING' NOT NULL,
    REVIEW_MODE         VARCHAR(20)   DEFAULT 'comprehensive' NOT NULL,
    CUSTOM_CRITERIA     VARCHAR(200),
    INSTRUCTIONS        VARCHAR(200),
    OVERALL_SUMMARY     TEXT,
    CAREER_PREPARATION_JSON TEXT,
    MODEL_NAME          VARCHAR(100),
    PROMPT_VERSION      VARCHAR(50),
    RESPONSE_VERSION    SMALLINT           DEFAULT 1 NOT NULL,
    ERROR_MESSAGE       VARCHAR(1000),
    CREATED_AT          TIMESTAMP(6)        DEFAULT LOCALTIMESTAMP NOT NULL,
    FINISHED_AT         TIMESTAMP(6),
    CONSTRAINT CK_REVIEW_MODE CHECK (
        REVIEW_MODE IN ('comprehensive', 'expression', 'consistency', 'jobFit', 'evidence', 'custom')
    ),
    CONSTRAINT CK_REVIEW_CUSTOM CHECK (
        (REVIEW_MODE = 'custom' AND CUSTOM_CRITERIA IS NOT NULL
            AND CUSTOM_CRITERIA ~ '[^[:space:]]')
        OR (REVIEW_MODE <> 'custom' AND CUSTOM_CRITERIA IS NULL)
    ),
    CONSTRAINT CK_REVIEW_VERSION CHECK (RESPONSE_VERSION > 0),
    CONSTRAINT CK_REVIEW_REQUEST CHECK (
        (REQUEST_ID IS NULL AND REQUEST_HASH IS NULL)
        OR (REQUEST_ID IS NOT NULL AND REQUEST_HASH IS NOT NULL)
    ),
    CONSTRAINT CK_REVIEW_PREPARATION_JSON CHECK (CAREER_PREPARATION_JSON IS JSON),
    CONSTRAINT CK_REVIEW_STATE CHECK (
        (REVIEW_STATUS = 'PROCESSING' AND FINISHED_AT IS NULL AND ERROR_MESSAGE IS NULL)
        OR (REVIEW_STATUS = 'COMPLETED' AND FINISHED_AT IS NOT NULL AND ERROR_MESSAGE IS NULL)
        OR (REVIEW_STATUS = 'FAILED' AND FINISHED_AT IS NOT NULL AND ERROR_MESSAGE IS NOT NULL)
    ),
    CONSTRAINT CK_REVIEW_TIME CHECK (FINISHED_AT >= CREATED_AT)
);
CREATE INDEX IDX_REVIEW_USER_DATE ON T_DOCUMENT_REVIEW(USER_NUM, CREATED_AT DESC, REVIEW_NUM DESC);
CREATE UNIQUE INDEX UQ_REVIEW_USER_REQUEST ON T_DOCUMENT_REVIEW(
    USER_NUM, REQUEST_ID
);

-- 3-2. 첨삭 당시 문서 스냅샷 및 개별 요약
CREATE TABLE T_REVIEW_DOCUMENT (
    REVIEW_DOCUMENT_NUM BIGINT          DEFAULT nextval('seq_t_review_document') PRIMARY KEY,
    REVIEW_NUM          BIGINT          NOT NULL REFERENCES T_DOCUMENT_REVIEW(REVIEW_NUM) ON DELETE CASCADE,
    DOCUMENT_TYPE       VARCHAR(20)   NOT NULL,
    SOURCE_DOCUMENT_NUM BIGINT          NOT NULL,
    DOCUMENT_TITLE      VARCHAR(200)  NOT NULL,
    SOURCE_UPDATED_AT   TIMESTAMP,
    SOURCE_SNAPSHOT_JSON TEXT               NOT NULL,
    ORIGINAL_FILE_NAME  VARCHAR(255),
    PDF_SNAPSHOT        BYTEA,
    DOCUMENT_SUMMARY    TEXT,
    CONSTRAINT UQ_REVIEW_DOC_TYPE UNIQUE (REVIEW_NUM, DOCUMENT_TYPE),
    CONSTRAINT UQ_REVIEW_DOC_PAIR UNIQUE (REVIEW_NUM, REVIEW_DOCUMENT_NUM),
    CONSTRAINT CK_REVIEW_DOC_TYPE CHECK (
        DOCUMENT_TYPE IN ('resume', 'cover-letter', 'portfolio')
    ),
    CONSTRAINT CK_REVIEW_DOC_SOURCE CHECK (SOURCE_DOCUMENT_NUM > 0),
    CONSTRAINT CK_REVIEW_DOC_JSON CHECK (SOURCE_SNAPSHOT_JSON IS JSON)
);

-- 3-3. 서류 전체 및 문서별 강점
CREATE TABLE T_REVIEW_STRENGTH (
    STRENGTH_NUM        BIGINT          DEFAULT nextval('seq_t_review_strength') PRIMARY KEY,
    REVIEW_NUM          BIGINT          NOT NULL REFERENCES T_DOCUMENT_REVIEW(REVIEW_NUM) ON DELETE CASCADE,
    REVIEW_DOCUMENT_NUM BIGINT,
    DISPLAY_ORDER       INTEGER           NOT NULL,
    STRENGTH_CONTENT    TEXT                NOT NULL,
    STRENGTH_REASON     TEXT,
    STRENGTH_SUGGESTION TEXT,
    STRENGTH_SOURCES_JSON TEXT,
    CONSTRAINT CK_REVIEW_STR_SOURCES_JSON CHECK (STRENGTH_SOURCES_JSON IS JSON),
    CONSTRAINT FK_REVIEW_STR_DOC FOREIGN KEY (REVIEW_NUM, REVIEW_DOCUMENT_NUM)
        REFERENCES T_REVIEW_DOCUMENT(REVIEW_NUM, REVIEW_DOCUMENT_NUM) ON DELETE CASCADE,
    CONSTRAINT CK_REVIEW_STR_ORDER CHECK (DISPLAY_ORDER > 0)
);
CREATE UNIQUE INDEX UQ_REVIEW_STR_ORDER ON T_REVIEW_STRENGTH(REVIEW_NUM, COALESCE(REVIEW_DOCUMENT_NUM, 0), DISPLAY_ORDER);
CREATE INDEX IDX_REVIEW_STR_DOC ON T_REVIEW_STRENGTH(REVIEW_NUM, REVIEW_DOCUMENT_NUM);

-- 3-4. 문서별 개선 제안
CREATE TABLE T_REVIEW_IMPROVEMENT (
    IMPROVEMENT_NUM     BIGINT          DEFAULT nextval('seq_t_review_improvement') PRIMARY KEY,
    REVIEW_DOCUMENT_NUM BIGINT          NOT NULL REFERENCES T_REVIEW_DOCUMENT(REVIEW_DOCUMENT_NUM) ON DELETE CASCADE,
    DISPLAY_ORDER       INTEGER           NOT NULL,
    SECTION_NAME        VARCHAR(500)  NOT NULL,
    IMPROVEMENT_TITLE   VARCHAR(500)  NOT NULL,
    ISSUE_CONTENT       TEXT                NOT NULL,
    ORIGINAL_CONTENT    TEXT                NOT NULL,
    SUGGESTED_CONTENT   TEXT                NOT NULL,
    REASON_CONTENT      TEXT                NOT NULL,
    CONSTRAINT UQ_REVIEW_IMP_ORDER UNIQUE (REVIEW_DOCUMENT_NUM, DISPLAY_ORDER),
    CONSTRAINT CK_REVIEW_IMP_ORDER CHECK (DISPLAY_ORDER > 0)
);

-- 3-5. 서류 간 일관성 검토
CREATE TABLE T_REVIEW_CONSISTENCY (
    CONSISTENCY_NUM     BIGINT          DEFAULT nextval('seq_t_review_consistency') PRIMARY KEY,
    REVIEW_NUM          BIGINT          NOT NULL REFERENCES T_DOCUMENT_REVIEW(REVIEW_NUM) ON DELETE CASCADE,
    DISPLAY_ORDER       INTEGER           NOT NULL,
    ISSUE_TYPE          VARCHAR(30)   NOT NULL,
    ISSUE_TITLE         VARCHAR(500)  NOT NULL,
    RECOMMENDATION      TEXT                NOT NULL,
    CONSTRAINT UQ_REVIEW_CON_PAIR UNIQUE (REVIEW_NUM, CONSISTENCY_NUM),
    CONSTRAINT UQ_REVIEW_CON_ORDER UNIQUE (REVIEW_NUM, DISPLAY_ORDER),
    CONSTRAINT CK_REVIEW_CON_ORDER CHECK (DISPLAY_ORDER > 0),
    CONSTRAINT CK_REVIEW_CON_TYPE CHECK (
        ISSUE_TYPE IN ('mismatch', 'missingEvidence', 'needsConfirmation')
    )
);

-- 3-6. 일관성 항목별 비교 근거 원문
CREATE TABLE T_REVIEW_SOURCE (
    CONSISTENCY_NUM     BIGINT          NOT NULL,
    DISPLAY_ORDER       INTEGER           NOT NULL,
    REVIEW_NUM          BIGINT          NOT NULL,
    REVIEW_DOCUMENT_NUM BIGINT          NOT NULL,
    SECTION_NAME        VARCHAR(500)  NOT NULL,
    SOURCE_CONTENT      TEXT                NOT NULL,
    PAGE_NUMBER         INTEGER,
    CONSTRAINT PK_REVIEW_SOURCE PRIMARY KEY (CONSISTENCY_NUM, DISPLAY_ORDER),
    CONSTRAINT FK_REVIEW_SRC_ISSUE FOREIGN KEY (REVIEW_NUM, CONSISTENCY_NUM)
        REFERENCES T_REVIEW_CONSISTENCY(REVIEW_NUM, CONSISTENCY_NUM) ON DELETE CASCADE,
    CONSTRAINT FK_REVIEW_SRC_DOC FOREIGN KEY (REVIEW_NUM, REVIEW_DOCUMENT_NUM)
        REFERENCES T_REVIEW_DOCUMENT(REVIEW_NUM, REVIEW_DOCUMENT_NUM) ON DELETE CASCADE,
    CONSTRAINT CK_REVIEW_SRC_ORDER CHECK (DISPLAY_ORDER > 0),
    CONSTRAINT CK_REVIEW_SRC_PAGE CHECK (PAGE_NUMBER > 0)
);
CREATE INDEX IDX_REVIEW_SRC_ISSUE ON T_REVIEW_SOURCE(REVIEW_NUM, CONSISTENCY_NUM);
CREATE INDEX IDX_REVIEW_SRC_DOC ON T_REVIEW_SOURCE(REVIEW_NUM, REVIEW_DOCUMENT_NUM);

