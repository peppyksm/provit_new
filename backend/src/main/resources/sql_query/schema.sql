CREATE INDEX IDX_SCRAP_USER ON T_JOB_SCRAP(USER_NUM);


-- ================================================================================
-- 6. 커뮤니티 및 스터디 도메인
-- ================================================================================

-- 6-1. 게시판 카테고리 종류
CREATE TABLE T_CATEGORY (
    CATEGORY_NUM         INTEGER           DEFAULT nextval('seq_t_category') PRIMARY KEY,
    CATEGORY_NAME        VARCHAR(100)       NOT NULL
);

-- 6-2. 커뮤니티 게시글
CREATE TABLE T_POST (
    POST_NUM             BIGINT          DEFAULT nextval('seq_t_post') PRIMARY KEY,
    CATEGORY_NUM         INTEGER           NOT NULL REFERENCES T_CATEGORY(CATEGORY_NUM) ON DELETE CASCADE,
    USER_NUM             INTEGER           NOT NULL REFERENCES T_USER(USER_NUM) ON DELETE CASCADE,
    POST_TITLE           VARCHAR(300)       NOT NULL,
    POST_CONTENT         VARCHAR(4000) CHECK (octet_length(POST_CONTENT) <= 4000),
    POST_LIKE_COUNT      INTEGER           DEFAULT 0 NOT NULL,
    VIEW_COUNT           INTEGER           DEFAULT 0 NOT NULL,
    POST_FILE            VARCHAR(500),
    POST_DATE            TIMESTAMP                DEFAULT LOCALTIMESTAMP NOT NULL
);
CREATE INDEX IDX_POST_CATEGORY ON T_POST(CATEGORY_NUM);
CREATE INDEX IDX_POST_USER ON T_POST(USER_NUM);

-- 6-3. 게시글 좋아요 (N:M 해소, 복합 기본키)
CREATE TABLE T_POST_LIKE (
    POST_NUM             BIGINT          NOT NULL REFERENCES T_POST(POST_NUM) ON DELETE CASCADE,
    USER_NUM             INTEGER           NOT NULL REFERENCES T_USER(USER_NUM) ON DELETE CASCADE,
    CREATED_AT           TIMESTAMP                DEFAULT LOCALTIMESTAMP NOT NULL,
    PRIMARY KEY (POST_NUM, USER_NUM)
);

-- 6-4. 게시글 댓글
CREATE TABLE T_COMMENT (
    COMMENT_NUM          BIGINT          DEFAULT nextval('seq_t_comment') PRIMARY KEY,
    POST_NUM             BIGINT          NOT NULL REFERENCES T_POST(POST_NUM) ON DELETE CASCADE,
    USER_NUM             INTEGER           NOT NULL REFERENCES T_USER(USER_NUM) ON DELETE CASCADE,
    COMMENT_CONTENT      VARCHAR(2000)      NOT NULL,
    COMMENT_DATE         TIMESTAMP                DEFAULT LOCALTIMESTAMP NOT NULL,
    PARENT_COMMENT_NUM   BIGINT          REFERENCES T_COMMENT(COMMENT_NUM),
    IS_DELETED           SMALLINT           DEFAULT 0 NOT NULL
);
CREATE INDEX IDX_COMMENT_POST ON T_COMMENT(POST_NUM);
CREATE INDEX IDX_COMMENT_USER ON T_COMMENT(USER_NUM);

-- 6-5. 스터디 모집 방
CREATE TABLE T_STUDY (
    STUDY_NUM            BIGINT          DEFAULT nextval('seq_t_study') PRIMARY KEY,
    USER_NUM             INTEGER           NOT NULL REFERENCES T_USER(USER_NUM) ON DELETE CASCADE,
    STUDY_NAME           VARCHAR(200)       NOT NULL,
    STUDY_EXPLAIN        VARCHAR(2000),
    MAX_MEMBERS          SMALLINT           DEFAULT 10 NOT NULL CHECK (MAX_MEMBERS >= 2),
    STUDY_CREATE_DATE    TIMESTAMP                DEFAULT LOCALTIMESTAMP NOT NULL
);

-- 6-6. 스터디 참여자 명단 (복합 기본키)
CREATE TABLE T_STUDY_MEMBER (
    STUDY_NUM            BIGINT          NOT NULL REFERENCES T_STUDY(STUDY_NUM) ON DELETE CASCADE,
    USER_NUM             INTEGER           NOT NULL REFERENCES T_USER(USER_NUM) ON DELETE CASCADE,
    STUDY_JOIN_DATE      DATE                DEFAULT LOCALTIMESTAMP NOT NULL,
    PRIMARY KEY (STUDY_NUM, USER_NUM)
);

-- 6-7. 신고 내역 관리 (T_REPORT)
CREATE TABLE T_REPORT (
    REPORT_NUM           BIGINT          DEFAULT nextval('seq_t_report') PRIMARY KEY,
    REPORTER_NUM         INTEGER           REFERENCES T_USER(USER_NUM) ON DELETE SET NULL,
    TARGET_TYPE          VARCHAR(20)        NOT NULL, -- 'POST' or 'COMMENT'
    TARGET_NUM           BIGINT          NOT NULL,
    REPORT_REASON        VARCHAR(100)       NOT NULL,
    REPORT_STATUS        VARCHAR(20)        DEFAULT 'PENDING' NOT NULL,
    REPORT_DATE          TIMESTAMP                DEFAULT LOCALTIMESTAMP NOT NULL
);

CREATE INDEX IDX_REPORT_STATUS ON T_REPORT(REPORT_STATUS);
CREATE INDEX IDX_REPORT_TARGET ON T_REPORT(TARGET_TYPE, TARGET_NUM);

