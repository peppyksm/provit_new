    DESIRED_WORK_TYPE    VARCHAR(100),
    CREATED_AT           TIMESTAMP                DEFAULT LOCALTIMESTAMP NOT NULL,
    UPDATED_AT           TIMESTAMP                DEFAULT LOCALTIMESTAMP NOT NULL
);
