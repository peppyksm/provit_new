-- 1. 회원 및 직무 도메인
-- ================================================================================

-- 1-1. 대분류 직군 테이블
CREATE TABLE T_OCCUPATION (
    OCCUPATION_CODE      VARCHAR(20)        PRIMARY KEY,
    OCCUPATION_NAME      VARCHAR(200)       NOT NULL
);

-- 1-2. 소분류 직무 테이블
CREATE TABLE T_JOB (
    JOB_CODE             VARCHAR(20)        PRIMARY KEY,
    OCCUPATION_CODE      VARCHAR(20)        NOT NULL REFERENCES T_OCCUPATION(OCCUPATION_CODE) ON DELETE CASCADE,
    JOB_NAME             VARCHAR(200)       NOT NULL
);

-- 1-3. 회원 기본 정보 테이블
CREATE TABLE T_USER (
    USER_NUM             INTEGER           DEFAULT nextval('seq_t_user') PRIMARY KEY,
    USER_NAME            VARCHAR(100)       NOT NULL,
    USER_NICKNAME        VARCHAR(100)       NOT NULL,
    USER_BIRTH_DATE      DATE,
    USER_EMAIL           VARCHAR(200)       NOT NULL UNIQUE,
    USER_PW              VARCHAR(255)       NOT NULL,
    USER_REGISTER_DATE   TIMESTAMP                DEFAULT LOCALTIMESTAMP NOT NULL,
    USER_TYPE            VARCHAR(30)        DEFAULT 'USER',
    USER_IS_DELETED      SMALLINT           DEFAULT 0 NOT NULL,
    USER_TOKEN_VERSION   INTEGER           DEFAULT 0 NOT NULL,
    BLOCKED_DATE         TIMESTAMP,
    MAIN_RESUME_NUM      BIGINT,
    OCCUPATION_CODE      VARCHAR(20)        REFERENCES T_OCCUPATION(OCCUPATION_CODE) ON DELETE SET NULL,
    JOB_CODE             VARCHAR(20)        REFERENCES T_JOB(JOB_CODE) ON DELETE SET NULL
);

-- 탈퇴 회원의 닉네임은 재사용할 수 있고, 활성 회원끼리만 중복을 막는다.
CREATE UNIQUE INDEX UQ_T_USER_ACTIVE_NICKNAME
ON T_USER (USER_NICKNAME) WHERE USER_IS_DELETED = 0;

-- 로그인 세션별 Refresh Token 식별자 보관. JWT 원문은 저장하지 않는다.
CREATE TABLE T_REFRESH_TOKEN (
    TOKEN_ID             VARCHAR(36)        PRIMARY KEY,
    USER_NUM             INTEGER           NOT NULL REFERENCES T_USER(USER_NUM) ON DELETE CASCADE,
    EXPIRES_AT           TIMESTAMP           NOT NULL
);

CREATE INDEX IDX_REFRESH_TOKEN_EXPIRES_AT ON T_REFRESH_TOKEN(EXPIRES_AT);


